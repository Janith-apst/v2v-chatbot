#!/usr/bin/env node
// One-shot transform: reads data/Maptivate-View–Access-Map.csv and writes
// src/data/maptivate.ts. Run manually when the CSV changes.
//
//   node scripts/build-maptivate.mjs

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, "..")
const CSV_PATH = resolve(ROOT, "data/Maptivate-View–Access-Map.csv")
const OUT_PATH = resolve(ROOT, "src/data/maptivate.ts")

function parseCsv(text) {
  // Strip UTF-8 BOM.
  if (text.charCodeAt(0) === 0xfeff) text = text.slice(1)
  const rows = []
  let field = ""
  let row = []
  let inQuotes = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"'
          i++
        } else {
          inQuotes = false
        }
      } else {
        field += c
      }
    } else {
      if (c === '"') {
        inQuotes = true
      } else if (c === ",") {
        row.push(field)
        field = ""
      } else if (c === "\n") {
        row.push(field)
        rows.push(row)
        row = []
        field = ""
      } else if (c === "\r") {
        // skip
      } else {
        field += c
      }
    }
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field)
    rows.push(row)
  }
  return rows
}

function slugify(s) {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60)
}

function splitList(s) {
  return s
    .split(",")
    .map((x) => x.trim())
    .filter(Boolean)
}

function parseLatLng(s) {
  const m = s.match(/(-?\d+(?:\.\d+)?)\s*,\s*(-?\d+(?:\.\d+)?)/)
  if (!m) return null
  return { lat: parseFloat(m[1]), lng: parseFloat(m[2]) }
}

const csv = readFileSync(CSV_PATH, "utf8")
const rows = parseCsv(csv)
const header = rows[0]
const idx = (name) => header.indexOf(name)

const COL_TITLE = idx("Title of location or event")
const COL_LGA = idx("LGA")
const COL_ADDR = idx("Location/event full address")
const COL_LATLNG = idx("Latitude, Longitude")
const COL_BTYPE = idx("Building type")
const COL_ACCESS = idx("Access")
const COL_NOTES = idx("Accessibility notes")
const COL_SUMMARY = idx("Accessibility Summary")
const COL_CARERS = idx("Additional information for carers")

if ([COL_TITLE, COL_LGA, COL_LATLNG].some((i) => i < 0)) {
  throw new Error("CSV is missing one of the required columns")
}

const venues = []
for (let r = 1; r < rows.length; r++) {
  const row = rows[r]
  const title = (row[COL_TITLE] ?? "").trim()
  if (!title) continue
  const latlng = parseLatLng((row[COL_LATLNG] ?? "").trim())
  if (!latlng) continue
  venues.push({
    id: slugify(title),
    title,
    lga: (row[COL_LGA] ?? "").trim(),
    address: (row[COL_ADDR] ?? "").trim(),
    lat: latlng.lat,
    lng: latlng.lng,
    buildingType: (row[COL_BTYPE] ?? "").trim(),
    access: splitList(row[COL_ACCESS] ?? ""),
    accessibilityNotes: (row[COL_NOTES] ?? "").trim(),
    accessibilitySummary: (row[COL_SUMMARY] ?? "").trim(),
    carersInfo: (row[COL_CARERS] ?? "").trim(),
  })
}

const lgas = Array.from(new Set(venues.map((v) => v.lga))).sort()

const banner = `// Generated by scripts/build-maptivate.mjs from data/Maptivate-View–Access-Map.csv
// Re-run that script when the CSV changes. Do not edit by hand.
`

const out = `${banner}
export type Venue = {
  id: string
  title: string
  lga: string
  address: string
  lat: number
  lng: number
  buildingType: string
  access: string[]
  accessibilityNotes: string
  accessibilitySummary: string
  carersInfo: string
}

export const LGAS: string[] = ${JSON.stringify(lgas, null, 2)}

export const VENUES: Venue[] = ${JSON.stringify(venues, null, 2)}
`

writeFileSync(OUT_PATH, out, "utf8")
console.log(`Wrote ${OUT_PATH}: ${venues.length} venues across ${lgas.length} LGAs.`)
